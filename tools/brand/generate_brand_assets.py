#!/usr/bin/env python3
"""Generates the app's brand resources from the master Wadrova SVG collection.

The master SVGs stay the only source: this script copies their path data unchanged and only
places it (Android vector drawables, launcher icon layers) or rasterises it with rsvg-convert
(legacy Android launcher PNGs, iOS app icons). Run it again whenever the collection changes:

    python3 tools/brand/generate_brand_assets.py [path/to/wadrova-brand-svg]

Requires Python 3 and rsvg-convert (Homebrew: librsvg). It never writes to the collection.
"""

import copy
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BRAND = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT.parent / "wadrova-brand-svg"
SVG_NS = "{http://www.w3.org/2000/svg}"

COMPOSE_DRAWABLES = ROOT / "shared/src/commonMain/composeResources/drawable"
ANDROID_RES = ROOT / "androidApp/src/main/res"
IOS_APP_ICON = ROOT / "iosApp/iosApp/Assets.xcassets/AppIcon.appiconset"

# Each colourway is named for the ground it sits on: "ivory" art goes on light grounds.
SHARED_VECTORS = {
    "wadrova_symbol_ivory": "symbol/wadrova-symbol-ivory.svg",
    "wadrova_symbol_graphite": "symbol/wadrova-symbol-graphite.svg",
    "wadrova_compact_symbol_ivory": "compact/wadrova-compact-symbol-ivory.svg",
    "wadrova_compact_symbol_graphite": "compact/wadrova-compact-symbol-graphite.svg",
    "wadrova_lockup_horizontal_ivory": "lockup-horizontal/wadrova-lockup-horizontal-ivory.svg",
    "wadrova_lockup_horizontal_graphite": "lockup-horizontal/wadrova-lockup-horizontal-graphite.svg",
}

# Both platforms use the primary symbol on Ivory, matching the official app-icon art on iOS.
ICON_GROUND = "#F5F4F0"  # Ivory, the ground the ivory symbol is drawn for.
ICON_SYMBOL = "symbol/wadrova-symbol-ivory.svg"
ICON_MONOCHROME = "symbol/wadrova-symbol-mono.svg"
ICON_LEGACY_TILE = "app-icon/wadrova-app-icon-ivory.svg"

# Adaptive icons are 108 dp; masks can cut anything outside the central 66 dp circle. The symbol's
# leaf tips sit in two corners of its box, so the box diagonal has to fit that circle, with a margin.
ADAPTIVE_CANVAS = 108.0
ADAPTIVE_SAFE_DIAMETER = 62.0

LEGACY_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}

IOS_ICONS = {
    # iOS draws its own corner mask, so the tile is filled to the edges instead of pre-rounded.
    "app-icon-1024.png": ("app-icon/wadrova-app-icon-ivory.svg", None),
    "app-icon-dark-1024.png": ("app-icon/wadrova-app-icon-graphite.svg", None),
    # Tinted icons are greyscale art the system tints; the reversed colourway is already greyscale.
    "app-icon-tinted-1024.png": ("app-icon/wadrova-app-icon-ivory.svg", "symbol/wadrova-symbol-reversed.svg"),
}


def read_svg(relative):
    root = ET.parse(BRAND / relative).getroot()
    x, y, w, h = (float(v) for v in root.get("viewBox").split())
    return root, (x, y, w, h)


def rect_path(rect):
    w, h = float(rect.get("width")), float(rect.get("height"))
    r = float(rect.get("rx", 0))
    if r == 0:
        return f"M 0 0 H {w} V {h} H 0 Z"
    return (
        f"M {r} 0 H {w - r} A {r} {r} 0 0 1 {w} {r} V {h - r} A {r} {r} 0 0 1 {w - r} {h} "
        f"H {r} A {r} {r} 0 0 1 0 {h - r} V {r} A {r} {r} 0 0 1 {r} 0 Z"
    )


def shapes(root):
    """The drawable elements in paint order, as (path data, element)."""
    for element in root:
        tag = element.tag.replace(SVG_NS, "")
        if tag == "path":
            yield element.get("d"), element
        elif tag == "rect":
            yield rect_path(element), element
        elif tag not in ("title", "desc"):
            raise SystemExit(f"Unsupported SVG element <{tag}>; extend the converter before using it.")


def vector_path(data, element, indent="    "):
    attrs = [f'android:pathData="{data}"', f'android:fillColor="{element.get("fill")}"']
    if element.get("stroke"):
        attrs += [
            f'android:strokeColor="{element.get("stroke")}"',
            f'android:strokeWidth="{element.get("stroke-width", "1")}"',
            f'android:strokeLineJoin="{element.get("stroke-linejoin", "miter")}"',
        ]
    lines = f"\n{indent}    ".join(attrs)
    return f"{indent}<path\n{indent}    {lines} />"


def vector_drawable(relative):
    root, (_, _, w, h) = read_svg(relative)
    paths = "\n".join(vector_path(d, e) for d, e in shapes(root))
    return (
        f"<!-- Generated by tools/brand/generate_brand_assets.py from {relative}. Do not edit. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{w}dp"\n    android:height="{h}dp"\n'
        f'    android:viewportWidth="{w}"\n    android:viewportHeight="{h}">\n'
        f"{paths}\n</vector>\n"
    )


def centred_in_safe_zone(relative):
    """Scale and offset that centre the symbol's box in the adaptive icon's safe circle."""
    _, (_, _, w, h) = read_svg(relative)
    scale = ADAPTIVE_SAFE_DIAMETER / (w * w + h * h) ** 0.5
    return scale, (ADAPTIVE_CANVAS - w * scale) / 2, (ADAPTIVE_CANVAS - h * scale) / 2


def adaptive_layer(relative, monochrome=False):
    root, _ = read_svg(relative)
    scale, dx, dy = centred_in_safe_zone(relative)
    paths = "\n".join(vector_path(d, e, indent="        ") for d, e in shapes(root))
    if monochrome:
        # Only alpha matters in a monochrome layer; the mono art's lens stays a hole.
        paths = re.sub(r'(fill|stroke)Color="#[0-9A-Fa-f]{6}"', r'\1Color="#FFFFFFFF"', paths)
    return (
        f"<!-- Generated by tools/brand/generate_brand_assets.py from {relative}. Do not edit. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{ADAPTIVE_CANVAS:g}dp"\n    android:height="{ADAPTIVE_CANVAS:g}dp"\n'
        f'    android:viewportWidth="{ADAPTIVE_CANVAS:g}"\n    android:viewportHeight="{ADAPTIVE_CANVAS:g}">\n'
        f'    <group\n        android:translateX="{dx:.4f}"\n        android:translateY="{dy:.4f}"\n'
        f'        android:scaleX="{scale:.6f}"\n        android:scaleY="{scale:.6f}">\n'
        f"{paths}\n    </group>\n</vector>\n"
    )


def svg_element(data, element):
    attrs = f'd="{data}" fill="{element.get("fill")}"'
    if element.get("stroke"):
        attrs += f' stroke="{element.get("stroke")}" stroke-width="{element.get("stroke-width")}" stroke-linejoin="{element.get("stroke-linejoin")}"'
    return f"<path {attrs}/>"


def render(svg_text, size, out):
    with tempfile.NamedTemporaryFile("w", suffix=".svg", delete=False) as f:
        f.write(svg_text)
    subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), f.name, "-o", str(out)], check=True)
    Path(f.name).unlink()


def legacy_launcher_svg(round_icon):
    """The ivory app icon as published, or the same art on a full circle for round icons."""
    root, (_, _, w, h) = read_svg(ICON_LEGACY_TILE)
    body = []
    for data, element in shapes(root):
        if element.get("id") == "tile" and round_icon:
            body.append(f'<circle cx="{w / 2}" cy="{h / 2}" r="{w / 2}" fill="{element.get("fill")}"/>')
        else:
            body.append(svg_element(data, element))
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">{"".join(body)}</svg>'


def ios_icon_svg(tile_source, symbol_colours):
    """The published app icon with its tile squared off, optionally recoloured from another colourway."""
    root, (_, _, w, h) = read_svg(tile_source)
    colours = {}
    if symbol_colours:
        colour_root, _ = read_svg(symbol_colours)
        colours = {e.get("id"): e for _, e in shapes(colour_root)}
    body = []
    for data, element in shapes(root):
        if element.get("id") == "tile":
            if symbol_colours:
                continue  # Tinted icons are drawn on a clear ground that the system fills.
            body.append(f'<rect width="{w}" height="{h}" fill="{element.get("fill")}"/>')
            continue
        if element.get("id") in colours:
            source = colours[element.get("id")]
            element = copy.copy(element)
            element.set("fill", source.get("fill"))
            if element.get("stroke"):
                element.set("stroke", source.get("stroke"))
        body.append(svg_element(data, element))
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">{"".join(body)}</svg>'


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print("wrote", path.relative_to(ROOT))


def main():
    if not BRAND.is_dir():
        raise SystemExit(f"Brand collection not found at {BRAND}")

    for name, relative in SHARED_VECTORS.items():
        write(COMPOSE_DRAWABLES / f"{name}.xml", vector_drawable(relative))

    write(ANDROID_RES / "drawable/ic_launcher_foreground.xml", adaptive_layer(ICON_SYMBOL))
    write(ANDROID_RES / "drawable/ic_launcher_monochrome.xml", adaptive_layer(ICON_MONOCHROME, monochrome=True))
    write(
        ANDROID_RES / "values/ic_launcher_background.xml",
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
        "<!-- Generated by tools/brand/generate_brand_assets.py. Do not edit. -->\n"
        f'<resources>\n    <color name="ic_launcher_background">{ICON_GROUND}</color>\n</resources>\n',
    )
    for density, size in LEGACY_SIZES.items():
        for name, round_icon in (("ic_launcher", False), ("ic_launcher_round", True)):
            out = ANDROID_RES / f"mipmap-{density}/{name}.png"
            render(legacy_launcher_svg(round_icon), size, out)
            print("wrote", out.relative_to(ROOT))

    for filename, (tile, colours) in IOS_ICONS.items():
        render(ios_icon_svg(tile, colours), 1024, IOS_APP_ICON / filename)
        print("wrote", (IOS_APP_ICON / filename).relative_to(ROOT))


if __name__ == "__main__":
    main()
